@router.get("/repositories/{repository_id}")
def get_tracked_repository(repository_id: str, settings: Settings = Depends(_get_settings)) -> dict[str, Any]:
    persistence = _persistence(settings)
    record = persistence.get_repository(repository_id)
    if not record:
        raise HTTPException(status_code=404, detail="Tracked repository not found")
    return record


@router.post("/repositories")
def create_repository(payload: RepoCreateRequest, settings: Settings = Depends(_get_settings)) -> dict[str, Any]:
    topic = payload.topic.strip()
    if not topic:
        raise HTTPException(status_code=400, detail="topic is required")
    service = _github_service(settings)
    persistence = _persistence(settings)
    try:
        created = service.create_repository(topic, description=payload.description, private=payload.private)
        if persistence is not None and persistence.is_available:
            audit_repository_created(persistence, created, payload.project_id)
            record = persistence.create_repository_record(
                {
                    "repository_id": created["repository_id"],
                    "repository_name": created["repository_name"],
                    "repository_full_name": created["repository_full_name"],
                    "repository_owner": created["repository_owner"],
                    "repository_url": created["repository_url"],
                    "clone_url": created.get("clone_url"),
                    "default_branch": created["default_branch"],
                    "visibility": created["visibility"],
                    "project_id": payload.project_id,
                },
                project_id=payload.project_id,
            )
            created["id"] = record["id"]
            created["project_id"] = payload.project_id
        return created
    except GitHubError as exc:
        raise _github_error(exc)


@router.post("/repositories/{repository_id}/initialize")
def initialize_repository(repository_id: str, settings: Settings = Depends(_get_settings)) -> dict[str, Any]:
    persistence = _persistence(settings)
    record = persistence.get_repository(repository_id)
    if not record:
        raise HTTPException(status_code=404, detail="Tracked repository not found")
    service = _github_service(settings)
    try:
        result = service.initialize_repository(record["repository_full_name"], default_branch=record.get("default_branch", "main"))
        if persistence is not None and persistence.is_available:
            persistence.update_repository(
                repository_id,
                {
                    "default_branch": result["default_branch"],
                    "last_commit_sha": result["initial_commit_sha"],
                },
            )
            audit_initialized(persistence, record["repository_full_name"])
        return {**result, "repository_id": repository_id, "repository_url": record["repository_url"]}
    except GitHubError as exc:
        raise _github_error(exc)


@router.post("/repositories/{repository_id}/push")
def push_files(repository_id: str, payload: RepoPushRequest, settings: Settings = Depends(_get_settings)) -> dict[str, Any]:
    if not payload.files:
        raise HTTPException(status_code=400, detail="files is empty")
    total_bytes = sum(len(content.encode("utf-8")) for content in payload.files.values())
    if total_bytes > 25 * 1024 * 1024:
        raise HTTPException(status_code=413, detail="Push exceeds 25 MB limit")
    persistence = _persistence(settings)
    record = persistence.get_repository(repository_id)
    if not record:
        raise HTTPException(status_code=404, detail="Tracked repository not found")
    full_name = record["repository_full_name"]
    branch = payload.branch or record.get("default_branch", "main")
    message = payload.message or f"Push website files (David AI)"
    service = _github_service(settings)
    try:
        result = service.push_files(full_name, payload.files, branch=branch, message=message)
        if persistence is not None and persistence.is_available:
            persistence.update_repository(
                repository_id,
                {
                    "default_branch": result["branch"],
                    "last_commit_sha": result["last_commit_sha"],
                    "updated_at": __import__("datetime").datetime.now(__import__("datetime").timezone.utc).isoformat(),
                },
            )
            audit_files_pushed(persistence, full_name, len(payload.files), record.get("project_id"))
            if result["last_commit_sha"]:
                audit_commit_created(persistence, full_name, result["last_commit_sha"], record.get("project_id"))
        return {
            "repository_id": repository_id,
            "repository_full_name": full_name,
            "repository_url": record["repository_url"],
            "branch": result["branch"],
            "last_commit_sha": result["last_commit_sha"],
            "files_pushed": result["files_pushed"],
        }
    except GitHubError as exc:
        raise _github_error(exc)


@router.post("/repositories/{repository_id}/update")
def update_repository(repository_id: str, payload: RepoUpdateRequest, settings: Settings = Depends(_get_settings)) -> dict[str, Any]:
    persistence = _persistence(settings)
    record = persistence.get_repository(repository_id)
    if not record:
        raise HTTPException(status_code=404, detail="Tracked repository not found")
    patch: dict[str, Any] = {}
    if payload.last_commit_sha:
        patch["last_commit_sha"] = payload.last_commit_sha
    if payload.deployment_provider is not None:
        patch["deployment_provider"] = payload.deployment_provider
    if payload.deployment_url is not None:
        patch["deployment_url"] = payload.deployment_url
    if payload.deployment_status is not None:
        patch["deployment_status"] = payload.deployment_status
    if not patch:
        raise HTTPException(status_code=400, detail="No updatable fields provided")
    updated = persistence.update_repository(repository_id, patch)
    if updated is None:
        raise HTTPException(status_code=500, detail="Failed to update repository record")
    if persistence is not None and persistence.is_available:
        audit_repository_updated(persistence, record["repository_full_name"], "metadata update")
    return updated


@router.get("/audit")
def list_audit_events(limit: int = Query(50, ge=1, le=200), settings: Settings = Depends(_get_settings)) -> list[dict[str, Any]]:
    persistence = _persistence(settings)
    if persistence is None or not persistence.is_available:
        raise HTTPException(status_code=503, detail="Database persistence is not available")
    events = persistence.list_audit_events(limit=limit)
    return [{"id": e.get("id"), "event": e.get("event"), "details": _safe_details(e.get("details")), "created_at": e.get("created_at")} for e in events]
